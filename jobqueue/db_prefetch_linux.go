package jobqueue

import "golang.org/x/sys/unix"

// fileOnNFS says if the file at path is on NFS, where taking a lock on it (as
// bbolt does at open) makes the client drop its cached pages of the file.
func fileOnNFS(path string) bool {
	var st unix.Statfs_t
	if err := unix.Statfs(path, &st); err != nil {
		return false
	}

	return st.Type == unix.NFS_SUPER_MAGIC
}
